-- key unless the migration ends with its own REVOKE. This check catches that.
--
-- Run it: after every migration that creates, drops or re-creates a function, view or table in public, or changes a
-- policy or a grant (paste the result into the PR). It also runs every day at 07:30 UTC (pg_cron job
